const menu = document.querySelector(".menu");
 const menuMain = menu.querySelector(".menu-main");
 const goBack = menu.querySelector(".go-back");
 const menuTrigger = document.querySelector(".mobile-menu-trigger");
 const closeMenu = menu.querySelector(".mobile-menu-close");
 let subMenu;
 menuMain.addEventListener("click", (e) =>{
 	if(!menu.classList.contains("active")){
 		return;
 	}
   if(e.target.closest(".menu-item-has-children")){
   	 const hasChildren = e.target.closest(".menu-item-has-children");
      showSubMenu(hasChildren);
   }
 });
 goBack.addEventListener("click",() =>{
 	 hideSubMenu();
 })
 menuTrigger.addEventListener("click",() =>{
 	 toggleMenu();
 })
 closeMenu.addEventListener("click",() =>{
 	 toggleMenu();
 })
 document.querySelector(".menu-overlay").addEventListener("click",() =>{
 	toggleMenu();
 })
 function toggleMenu(){
 	menu.classList.toggle("active");
 	document.querySelector(".menu-overlay").classList.toggle("active");
 }
 function showSubMenu(hasChildren){
    subMenu = hasChildren.querySelector(".sub-menu");
    subMenu.classList.add("active");
    subMenu.style.animation = "slideLeft 0.5s ease forwards";
    const menuTitle = hasChildren.querySelector("i").parentNode.childNodes[0].textContent;
    menu.querySelector(".current-menu-title").innerHTML=menuTitle;
    menu.querySelector(".mobile-menu-head").classList.add("active");
 }

 function  hideSubMenu(){  
    subMenu.style.animation = "slideRight 0.5s ease forwards";
    setTimeout(() =>{
       subMenu.classList.remove("active");	
    },300); 
    menu.querySelector(".current-menu-title").innerHTML="";
    menu.querySelector(".mobile-menu-head").classList.remove("active");
 }
 
 window.onresize = function(){
 	if(this.innerWidth >991){
 		if(menu.classList.contains("active")){
 			toggleMenu();
 		}

 	}
 }

 document.addEventListener("DOMContentLoaded", function () {
    const menu = document.querySelector(".header .menu");
    const trigger = document.querySelector(".mobile-menu-trigger");
    const close = document.querySelector(".mobile-menu-close");
    const overlay = document.querySelector(".menu-overlay");
    const submenuLinks = document.querySelectorAll(".menu li.menu-item-has-children > a");
    const backButtons = document.querySelectorAll(".go-back");

    // Open menu
    trigger.addEventListener("click", () => {
        menu.classList.add("active");
        overlay.classList.add("active");
    });

    // Close menu
    close.addEventListener("click", () => {
        menu.classList.remove("active");
        overlay.classList.remove("active");
        closeAllSubmenus();
    });

    // Handle sub-menu opening
    submenuLinks.forEach(link => {
        link.addEventListener("click", function (e) {
            const parentLi = this.parentElement;
            if (window.innerWidth < 992) {
                e.preventDefault(); // Prevent navigation
                const submenu = parentLi.querySelector(".sub-menu");
                if (submenu) {
                    submenu.classList.add("active");
                    menu.querySelector(".mobile-menu-head").classList.add("active");
                    const title = parentLi.querySelector("a").textContent;
                    menu.querySelector(".current-menu-title").textContent = title.trim();
                }
            }
        });
    });

    // Go back button
    backButtons.forEach(btn => {
        btn.addEventListener("click", () => {
            menu.querySelector(".mobile-menu-head").classList.remove("active");
            closeAllSubmenus();
        });
    });

    // Helper: close all submenus
    function closeAllSubmenus() {
        document.querySelectorAll(".header .sub-menu").forEach(submenu => {
            submenu.classList.remove("active");
        });
    }
});


















